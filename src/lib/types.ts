export type Role = 'top' | 'jungle' | 'mid' | 'bot' | 'support';
export type DamageType = 'ad' | 'ap' | 'mixed';
export type Difficulty = 'easy' | 'medium' | 'hard';
export type Advantage = 'player' | 'enemy' | 'even';
export type WindowType = 'dodge' | 'punish' | 'counter';
export type IconType = 'champion' | 'item' | 'rune' | 'spell' | 'ability';
export type RunePath = 'keystone' | 'precision' | 'domination' | 'resolve' | 'inspiration';

export interface Ability {
  name: string;
  description: string;
  cooldown?: number[];
}

export interface ChampionAbilities {
  passive: Ability;
  q: Ability;
  w: Ability;
  e: Ability;
  r: Ability;
}

export type RangeType = 'melee' | 'ranged';

/** Base stats at level 1 plus per-level growth (official patch data). */
export interface ChampionStats {
  hp: number;
  hpPerLevel: number;
  hpRegen: number;
  hpRegenPerLevel: number;
  mana: number;
  manaPerLevel: number;
  manaRegen: number;
  manaRegenPerLevel: number;
  attackDamage: number;
  attackDamagePerLevel: number;
  armor: number;
  armorPerLevel: number;
  magicResist: number;
  magicResistPerLevel: number;
  moveSpeed: number;
  attackRange: number;
  rangeType: RangeType;
}

/** One "Counter their build" recommendation derived from the enemy's items. */
export interface BuildAdaptation {
  itemId: string;
  reason: string;
}

export interface Champion {
  id: string;
  name: string;
  title: string;
  commonLanes: Role[];
  damageType: DamageType;
  color: string;
  icon: string;
  hasHealing: boolean;
  hasCC: boolean;
  defaultRunes: string[];
  defaultSpells: string[];
  abilities: ChampionAbilities;
  powerSpikes: string[];
  stats: ChampionStats;
}

export interface Item {
  id: string;
  name: string;
  cost: number;
  stats: Record<string, number>;
  passive: string;
  category: string;
  icon: string;
  buildsInto: string[];
}

export interface Rune {
  id: string;
  name: string;
  path: RunePath;
  description: string;
  icon: string;
}

export interface Spell {
  id: string;
  name: string;
  description: string;
  icon: string;
}

export interface BuildStep {
  itemId: string;
  timing: string;
  reason: string;
}

export interface AvoidItem {
  itemId: string;
  reason: string;
}

export interface PowerSpikeEntry {
  phase: string;
  advantage: Advantage;
  detail: string;
}

export interface AbilityWindow {
  type: WindowType;
  ability: string;
  detail: string;
}

export interface Matchup {
  id: string;
  playerChampion: string;
  enemyChampion: string;
  role: Role;
  difficulty: Difficulty;
  summary: string;
  itemBuild: { corePath: BuildStep[]; avoidItems: AvoidItem[] };
  runeSwap: { default: string[]; recommended: string[]; reason: string };
  summonerSpells: { default: string[]; recommended: string[]; reason: string };
  powerSpikes: PowerSpikeEntry[];
  abilityWindows: AbilityWindow[];
  waveManagement: string;
  lastUpdated: string;
  patchVersion: string;
}

/** Curated matchup + fallback engine output share this shape. */
export interface CounterGuide extends Matchup {
  autoGenerated: boolean;
}
