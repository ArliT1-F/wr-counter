import { useNavigate } from 'react-router-dom';
import GameIcon from './GameIcon';
import DifficultyBadge from './DifficultyBadge';
import ChampionStatsStrip from './ChampionStatsStrip';
import ItemBuildSection from './ItemBuildSection';
import RuneSwapSection from './RuneSwapSection';
import SummonerSpellsSection from './SummonerSpellsSection';
import PowerSpikeTimeline from './PowerSpikeTimeline';
import AbilityWindowCard from './AbilityWindowCard';
import AbilityReferenceSection from './AbilityReferenceSection';
import FeedbackRow from './FeedbackRow';
import ShareButton from './ShareButton';
import CollapsibleSection from './CollapsibleSection';
import { ICON_BASE_URL, PATCH_VERSION } from '../lib/constants';
import { getChampion, matchupIdFor } from '../lib/dataLoader';
import { isFavorite, toggleFavorite } from '../lib/storage';
import { t } from '../lib/strings';
import { track } from '../lib/analytics';
import { useState } from 'react';
import type { CounterGuide } from '../lib/types';

interface CounterCardProps {
  guide: CounterGuide;
  /** True when navigating from the swap button — plays the 180° rotation. */
  swapAnimation?: boolean;
}

/** The core single-screen counter card. */
export default function CounterCard({ guide, swapAnimation = false }: CounterCardProps) {
  const navigate = useNavigate();
  const [fav, setFav] = useState(() => isFavorite(guide.id));
  const [spinning, setSpinning] = useState(false);

  const player = getChampion(guide.playerChampion);
  const enemy = getChampion(guide.enemyChampion);
  if (!player || !enemy) return null;

  const swapId = matchupIdFor(enemy.id, player.id, guide.role);

  function handleSwap() {
    track('swap', { matchup: guide.id });
    setSpinning(true);
    window.setTimeout(() => {
      navigate(`/counter/${swapId}`, { state: { swapped: true } });
      setSpinning(false);
    }, 200);
  }

  function handleFavorite() {
    const next = toggleFavorite(guide.id);
    setFav(next);
  }

  const iconClass = spinning || swapAnimation ? 'swap-anim' : '';

  return (
    <article aria-label={`${player.name} vs ${enemy.name}`} className="page-enter max-w-[720px] mx-auto">
      {/* Sticky header */}
      <header className="sticky top-0 z-30 -mx-4 px-4 py-3 bg-bg-primary/95 backdrop-blur border-b border-white/10">
        <div className="flex items-center gap-2.5 flex-wrap">
          <span className={`inline-flex items-center gap-2 ${iconClass}`}>
            <GameIcon
              src={`${ICON_BASE_URL}/champions/${player.icon}`}
              fallbackLetter={player.name[0]}
              fallbackColor={player.color}
              size={44}
              type="champion"
            />
            <span className="text-text-secondary font-semibold text-sm">{t('card.vs')}</span>
            <GameIcon
              src={`${ICON_BASE_URL}/champions/${enemy.icon}`}
              fallbackLetter={enemy.name[0]}
              fallbackColor={enemy.color}
              size={44}
              type="champion"
            />
          </span>
          <div className="flex flex-col">
            <h1 className="font-bold text-text-primary leading-tight">
              {player.name} <span className="text-text-muted text-sm">{t('card.vs')}</span> {enemy.name}
            </h1>
            <div className="flex items-center gap-2">
              <DifficultyBadge difficulty={guide.difficulty} />
              <span className="text-xs text-text-muted">{t(`roles.${guide.role}`)}</span>
            </div>
          </div>
          <div className="flex items-center gap-2 ml-auto">
            <button
              type="button"
              onClick={handleSwap}
              aria-label={t('card.swap')}
              title={t('card.swapTooltip')}
              className="pressable min-h-tap min-w-tap px-3 rounded-sm bg-bg-elevated border border-teal/40 text-teal text-sm font-semibold hover:border-teal"
            >
              🔄 {t('card.swap')}
            </button>
            <ShareButton player={player} enemy={enemy} role={guide.role} summary={guide.summary} />
            <button
              type="button"
              onClick={handleFavorite}
              aria-label={fav ? t('card.favoriteRemove') : t('card.favoriteAdd')}
              aria-pressed={fav}
              className={`pressable min-h-tap min-w-tap px-2 rounded-sm border text-lg ${
                fav ? 'bg-gold/20 border-gold text-gold' : 'bg-bg-elevated border-white/10 text-text-secondary'
              }`}
            >
              {fav ? '★' : '☆'}
            </button>
          </div>
        </div>
      </header>

      {/* Auto-generated banner */}
      {guide.autoGenerated && (
        <div
          role="status"
          className="mt-4 rounded-md border border-orange/50 bg-orange/10 p-3.5 text-sm text-text-primary"
        >
          <p className="font-semibold mb-1">{t('card.autoGenerated')}</p>
          <p className="text-text-secondary">{t('card.autoBanner')}</p>
          <a
            href="https://github.com/ArliT1-F/wr-counter/issues/new"
            target="_blank"
            rel="noreferrer"
            className="inline-block mt-2 text-orange font-semibold underline min-h-tap leading-tap"
          >
            {t('card.autoBannerCta')} →
          </a>
        </div>
      )}

      {/* Summary */}
      <p className="mt-4 text-text-secondary bg-bg-card rounded-lg border border-white/5 p-4 leading-relaxed">
        {guide.summary}
      </p>

      <ChampionStatsStrip player={player} enemy={enemy} />

      <div className="mt-4 space-y-3">
        <ItemBuildSection guide={guide} />
        <RuneSwapSection guide={guide} />
        <SummonerSpellsSection guide={guide} />
        <PowerSpikeTimeline guide={guide} />
        <AbilityWindowCard guide={guide} />
        <AbilityReferenceSection guide={guide} />
        <CollapsibleSection title={t('card.waveManagement')} emoji="🌊" sectionKey="waveManagement">
          <p className="text-sm text-text-secondary leading-relaxed">{guide.waveManagement}</p>
          <FeedbackRow matchupId={guide.id} section="waveManagement" />
        </CollapsibleSection>
      </div>

      {/* Footer */}
      <footer className="mt-5 mb-2 flex items-center justify-between text-xs text-text-muted">
        <span>{t('card.lastUpdated', { version: guide.patchVersion || PATCH_VERSION })}</span>
        <a
          href="https://github.com/ArliT1-F/wr-counter/issues/new"
          target="_blank"
          rel="noreferrer"
          className="underline hover:text-text-secondary min-h-tap inline-flex items-center"
        >
          {t('app.footerFeedback')}
        </a>
      </footer>
    </article>
  );
}
