import { useEffect, useMemo } from 'react';
import { useLocation, useParams, Link } from 'react-router-dom';
import CounterCard from '../components/CounterCard';
import EnemyBuildPanel from '../components/EnemyBuildPanel';
import GameIcon from '../components/GameIcon';
import { getChampion, getCounterGuide, matchupIdFor } from '../lib/dataLoader';
import { generateBasicCounter } from '../lib/counterEngine';
import { pushRecent } from '../lib/storage';
import { t } from '../lib/strings';
import { track } from '../lib/analytics';
import { ICON_BASE_URL, PATCH_VERSION, TRENDING_MATCHUP_IDS } from '../lib/constants';
import type { CounterGuide, Role } from '../lib/types';

const VALID_ROLES: Role[] = ['top', 'jungle', 'mid', 'bot', 'support'];

/**
 * Parse "/counter/{player}-vs-{enemy}-{role}".
 * Champion ids may contain hyphens (miss-fortune), so split on the LAST hyphen
 * for the role and on the literal "-vs-" for the pair.
 */
export function parseMatchupSlug(slug: string): { playerId: string; enemyId: string; role: Role } | null {
  const lastDash = slug.lastIndexOf('-');
  if (lastDash <= 0) return null;
  const role = slug.slice(lastDash + 1) as Role;
  if (!VALID_ROLES.includes(role)) return null;
  const pair = slug.slice(0, lastDash);
  const vsIndex = pair.indexOf('-vs-');
  if (vsIndex <= 0) return null;
  const playerId = pair.slice(0, vsIndex);
  const enemyId = pair.slice(vsIndex + 4);
  if (!playerId || !enemyId || playerId === enemyId) return null;
  return { playerId, enemyId, role };
}

function setMeta(name: string, content: string, property = false) {
  const attr = property ? 'property' : 'name';
  let el = document.head.querySelector<HTMLMetaElement>(`meta[${attr}="${name}"]`);
  if (!el) {
    el = document.createElement('meta');
    el.setAttribute(attr, name);
    document.head.appendChild(el);
  }
  el.setAttribute('content', content);
}

function applySeoTags(guide: CounterGuide) {
  const player = getChampion(guide.playerChampion);
  const enemy = getChampion(guide.enemyChampion);
  if (!player || !enemy) return;
  const title = `${player.name} vs ${enemy.name} Counter Guide — Wild Rift Patch ${guide.patchVersion} | WR Counter`;
  const description = `How to counter ${enemy.name} as ${player.name} in Wild Rift. ${guide.itemBuild.corePath[0]?.reason ?? ''} ${guide.summary}`;
  document.title = title;
  setMeta('description', description);
  setMeta('og:title', title, true);
  setMeta('og:description', description, true);
  setMeta('og:url', window.location.href, true);
  setMeta('og:type', 'article', true);
  setMeta(
    'og:image',
    `${window.location.origin}/og/${guide.id}.png`,
    true,
  );
}

/** Screen 2: Counter Card — deep-linkable at /counter/{player}-vs-{enemy}-{role}. */
export default function CounterPage() {
  const { matchup } = useParams<{ matchup: string }>();
  const location = useLocation();
  const swapped = Boolean((location.state as { swapped?: boolean } | null)?.swapped);

  const parsed = matchup ? parseMatchupSlug(matchup) : null;
  const player = parsed ? getChampion(parsed.playerId) : undefined;
  const enemy = parsed ? getChampion(parsed.enemyId) : undefined;

  const guide: CounterGuide | null = useMemo(() => {
    if (!parsed || !player || !enemy) return null;
    return (
      getCounterGuide(matchupIdFor(player.id, enemy.id, parsed.role)) ??
      generateBasicCounter(player.id, enemy.id, parsed.role)
    );
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [matchup]);

  useEffect(() => {
    if (!guide) return;
    pushRecent(guide.id);
    track('pageview_matchup', { matchup: guide.id, auto: String(guide.autoGenerated) });
    applySeoTags(guide);
  }, [guide]);

  if (!guide || !player || !enemy) {
    return (
      <div className="page-enter max-w-md mx-auto mt-12 text-center p-6 bg-bg-card rounded-lg border border-white/10">
        <h1 className="text-xl font-bold text-text-primary">{t('card.notFoundTitle')}</h1>
        <p className="text-text-secondary mt-2">{t('card.notFoundBody')}</p>
        <Link
          to="/"
          className="pressable inline-flex items-center mt-4 min-h-tap px-5 rounded-sm bg-gold text-bg-primary font-semibold"
        >
          {t('card.backToSelect')}
        </Link>
      </div>
    );
  }

  return (
    <div className="lg:grid lg:grid-cols-[1fr_260px] lg:gap-6 lg:max-w-5xl lg:mx-auto">
      <div className="px-4">
        <CounterCard guide={guide} swapAnimation={swapped} />
        <EnemyBuildPanel
          matchupSlug={guide.id}
          player={player}
          enemy={enemy}
          alreadyBuilt={guide.itemBuild.corePath.map((x) => x.itemId)}
        />
      </div>

      <aside className="hidden lg:block px-2 pt-6">
        <div className="bg-bg-card rounded-lg border border-white/5 p-4">
          <h2 className="font-semibold text-text-primary mb-3">🔥 {t('card.trending')}</h2>
          <ul className="space-y-1.5">
            {TRENDING_MATCHUP_IDS.filter((id) => id !== guide.id).slice(0, 8).map((id) => {
              const [pair, r] = [id.slice(0, id.lastIndexOf('-')), id.slice(id.lastIndexOf('-') + 1)];
              const [pid = '', eid = ''] = pair.split('-vs-');
              const p = getChampion(pid);
              const e = getChampion(eid);
              if (!p || !e) return null;
              return (
                <li key={id}>
                  <Link to={`/counter/${id}`} className="pressable flex items-center gap-2 p-2 rounded-sm hover:bg-bg-elevated">
                    <GameIcon
                      src={`${ICON_BASE_URL}/champions/${p.icon}`}
                      fallbackLetter={p.name[0]}
                      fallbackColor={p.color}
                      size={26}
                      type="champion"
                    />
                    <GameIcon
                      src={`${ICON_BASE_URL}/champions/${e.icon}`}
                      fallbackLetter={e.name[0]}
                      fallbackColor={e.color}
                      size={26}
                      type="champion"
                    />
                    <span className="text-xs text-text-secondary truncate">
                      {p.name} vs {e.name}
                    </span>
                    <span className="ml-auto text-[10px] uppercase text-text-muted">{t(`roles.${r}`)}</span>
                  </Link>
                </li>
              );
            })}
          </ul>
          <Link to="/" className="pressable inline-block mt-4 text-sm text-gold underline min-h-tap leading-tap">
            {t('card.backToSelect')}
          </Link>
        </div>
        <p className="text-xs text-text-muted mt-3 px-1">
          {t('card.lastUpdated', { version: PATCH_VERSION })}
        </p>
      </aside>
    </div>
  );
}
